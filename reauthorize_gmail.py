#!/usr/bin/env python3
"""
Re-authorize Google from the host (your Mac).

OPENS A BROWSER WINDOW where you must sign in with the desired Google account
and grant the requested scopes. On success it writes a fresh, encrypted
token.pickle to backend/credentials/.

NOTE: the backend runtime no longer reads token.pickle (all credentials live
per-user in user_integrations). This script now only produces the input file
for the one-time migration: run backend/migrate_legacy_google_token.py (or
`docker compose exec backend python migrate_legacy_google_token.py`) to import
the token into the owner's user integration, after which the file is archived.

Prerequisite: a valid OAuth client at backend/credentials/credentials.json
(must be registered as an OAuth 2.0 "Desktop app" and include these scopes).

ONE-TIME SETUP (installs the Google OAuth lib into a throwaway venv):
    python3 -m venv /tmp/aichief-reauth-venv
    /tmp/aichief-reauth-venv/bin/pip install google-auth-oauthlib

Usage:
    python3 reauthorize_gmail.py
"""

import base64
import hashlib
import json
import os
import pickle
import socket
import sys
import threading
import urllib.parse
import webbrowser

import requests
from cryptography.fernet import Fernet
from google.oauth2.credentials import Credentials
from google_auth_oauthlib.flow import InstalledAppFlow

ROOT = os.path.dirname(os.path.abspath(__file__))
BACKEND = os.path.join(ROOT, "backend")
ENV_FILE = os.path.join(BACKEND, ".env")
SECRET_KEY_FILE = os.path.join(BACKEND, ".secret_key")
FALLBACK_SECRET_KEY = "change-this-to-a-random-secret-key"
CREDENTIALS_FILE = os.path.join(BACKEND, "credentials", "credentials.json")
TOKEN_FILE = os.path.join(BACKEND, "credentials", "token.pickle")

SCOPES = [
    "https://www.googleapis.com/auth/gmail.readonly",
    "https://www.googleapis.com/auth/classroom.courses.readonly",
    "https://www.googleapis.com/auth/classroom.coursework.me.readonly",
    "https://www.googleapis.com/auth/classroom.student-submissions.me.readonly",
    "https://www.googleapis.com/auth/calendar.events",
]

# The one scope without which the Gmail pipeline cannot operate at all.
SCOPE_GMAIL_READONLY = "https://www.googleapis.com/auth/gmail.readonly"


def _env_secret_key() -> str | None:
    if not os.path.exists(ENV_FILE):
        return None
    with open(ENV_FILE) as f:
        for line in f:
            line = line.strip()
            if line.startswith("SECRET_KEY="):
                _, _, value = line.partition("=")
                value = value.strip().strip('"').strip("'")
                return value or None
    return None


def _resolve_secret_key() -> str:
    value = _env_secret_key()
    if value and value != FALLBACK_SECRET_KEY and not value.startswith("change-this-to-"):
        return value
    if os.path.exists(SECRET_KEY_FILE):
        stored = open(SECRET_KEY_FILE).read().strip()
        if stored:
            return stored
    raise SystemExit(
        "ERROR: could not determine SECRET_KEY (no .env SECRET_KEY and no .secret_key).\n"
        "The backend normally creates backend/.secret_key on first run."
    )


def _fernet(secret: str) -> Fernet:
    key = base64.urlsafe_b64encode(hashlib.sha256(secret.encode()).digest())
    return Fernet(key)


def _encrypt_bytes(data: bytes, secret: str) -> bytes:
    return _fernet(secret).encrypt(data)


def _exchange_code(flow, code, redirect_uri, timeout=30):
    """Exchange the authorization code for tokens with a plain HTTPS POST.

    Mirrors the app's own google_auth.reauthorize() token exchange, but adds
    the PKCE ``code_verifier`` (generated by authorization_url) which Google
    requires for Desktop/Installed clients. Using a direct requests call (not
    oauthlib's fetch_token) avoids oauthlib's strict scope-ordering validation;
    we validate the required scopes ourselves afterwards."""
    resp = requests.post(
        flow.client_config["token_uri"],
        data={
            "client_id": flow.client_config["client_id"],
            "client_secret": flow.client_config["client_secret"],
            "code": code,
            "grant_type": "authorization_code",
            "redirect_uri": redirect_uri,
            "code_verifier": flow.code_verifier,
        },
        timeout=timeout,
    )
    data = resp.json()
    if "access_token" not in data:
        raise GoogleAuthError(f"Token exchange failed: {data.get('error', 'unknown')}")
    return data


class GoogleAuthError(RuntimeError):
    pass


def main():
    # This is a strict local-loopback OAuth flow: the callback server binds to
    # 127.0.0.1 and the token exchange itself goes to Google over https
    # (token_uri). oauthlib refuses to parse plain-http callback URIs by
    # default; the documented escape hatch for local callbacks is this env var.
    # It is scoped to this process only and never touches network traffic.
    os.environ["OAUTHLIB_INSECURE_TRANSPORT"] = "1"

    if not os.path.exists(CREDENTIALS_FILE):
        print(f"ERROR: credentials.json not found at {CREDENTIALS_FILE}")
        print("Download it from Google Cloud Console (APIs & Services > "
              "Credentials > OAuth 2.0 Client IDs > Desktop app).")
        sys.exit(1)

    secret = _resolve_secret_key()

    flow = InstalledAppFlow.from_client_secrets_file(CREDENTIALS_FILE, SCOPES)

    # Local loopback server to capture the OAuth redirect (like the app's
    # google_auth.reauthorize). Binds 127.0.0.1 on an ephemeral port.
    srv = socket.socket()
    srv.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    srv.bind(("127.0.0.1", 0))
    srv.settimeout(300)
    port = srv.getsockname()[1]
    srv.listen(1)
    redirect_uri = f"http://127.0.0.1:{port}/"

    # Match what the app's own google_auth.reauthorize() does and what
    # run_local_server() does internally: tell the flow which loopback
    # redirect to use BEFORE building the authorization URL. Use the loopback
    # IP literal (127.0.0.1) rather than the "localhost" hostname — oauthlib
    # treats "localhost:{port}" as insecure transport, but exempts the
    # 127.0.0.1 loopback literal for OAuth. Without setting flow.redirect_uri,
    # authorization_url() falls back to credentials.json's bare
    # "http://localhost" (no port) and Google rejects it ("invalid_request:
    # Missing required parameter: redirect_uri").
    flow.redirect_uri = redirect_uri

    # Do NOT include include_granted_scopes: we only want our 5 minimal scopes,
    # not previously-granted (broader) Gmail scopes.
    auth_url, _ = flow.authorization_url(
        access_type="offline", prompt="consent", include_granted_scopes="false"
    )

    result: dict = {}

    def _wait_for_code():
        try:
            conn, _ = srv.accept()
            req = conn.recv(4096).decode(errors="ignore")
            path = req.split(" ")[1] if " " in req else "/"
            body = (b"<html><body><h2>Authorization complete.</h2>"
                    b"<p>You can close this tab and return to AI Chief.</p></body></html>")
            conn.sendall(
                b"HTTP/1.1 200 OK\r\nContent-Type: text/html\r\nContent-Length: "
                + str(len(body)).encode() + b"\r\nConnection: close\r\n\r\n" + body
            )
            conn.close()
            result["query"] = urllib.parse.urlparse(path).query
        except Exception as e:
            result["error"] = str(e)
        finally:
            srv.close()

    print("A browser tab will open. Sign in with the Google account you want "
          "to connect and grant access, then you will be redirected back.")
    print("If no tab opens, open this URL in your browser and complete the "
          "Google consent screen:\n")
    print(auth_url)
    print()
    webbrowser.open(auth_url)
    thread = threading.Thread(target=_wait_for_code, daemon=True)
    thread.start()
    thread.join()

    if "error" in result:
        raise GoogleAuthError(f"Could not complete the authorization flow: {result['error']}")

    params = urllib.parse.parse_qs(result["query"])
    code = params.get("code", [None])[0]
    if not code:
        raise GoogleAuthError(
            f"Authorization failed: {params.get('error', ['unknown error'])[0]}"
        )

    data = _exchange_code(flow, code, redirect_uri)
    returned_scopes = set((data.get("scope", "") or "").split())
    missing = [s for s in SCOPES if s not in returned_scopes]

    # gmail.readonly is the essential scope: without it the Gmail pipeline
    # cannot work. The remaining scopes (calendar + classroom) are best-effort
    # — Google may withhold unapproved/restricted scopes from the OAuth
    # consent screen. Save what is granted so sync works for every granted
    # scope, and clearly report anything missing.
    if SCOPE_GMAIL_READONLY not in returned_scopes:
        raise GoogleAuthError(
            f"Authorization is missing the essential Gmail scope. "
            f"Granted: {sorted(returned_scopes)}"
        )

    if missing:
        print(
            "WARNING: Google did not grant these requested scopes (may be "
            "unapproved in the Google Cloud consent screen or restricted by "
            "your Workspace): "
            + ", ".join(missing)
        )

    creds = Credentials(
        token=data["access_token"],
        refresh_token=data.get("refresh_token"),
        token_uri=flow.client_config["token_uri"],
        client_id=flow.client_config["client_id"],
        client_secret=flow.client_config["client_secret"],
        scopes=(data.get("scope", "") or "").split(),
    )
    if not getattr(creds, "refresh_token", None):
        print("ERROR: no refresh_token returned. Re-run and grant access (don't decline).")
        sys.exit(1)

    payload = pickle.dumps(creds)
    os.makedirs(os.path.dirname(TOKEN_FILE), exist_ok=True)
    with open(TOKEN_FILE, "wb") as f:
        f.write(_encrypt_bytes(payload, secret))

    print(f"OK: new token saved to {TOKEN_FILE}")
    print("Scopes:", ", ".join(creds.scopes))
    print("Next: run backend/migrate_legacy_google_token.py to import this "
          "token into the owner's user integration.")


if __name__ == "__main__":
    main()
